# QS01 · 认识 PyMotion Lite
# PyMotion Lite 是一款面向机器人与智能硬件开发的控制设备。通过 Python SDK，用户
# 可以使用 USB 或 Wi-Fi 连接设备，并控制直流减速电机、PWM 舵机和 TTL 舵机，读取
# 传感器数据以及更新 OLED 显示内容。
#
# Quick Start 包含三个可运行例程：02 用于建立连接并读取设备状态，03 用于控制直流
# 减速电机，04 用于读取超声波距离并显示到 OLED。建议按顺序运行，以便先确认连接，
# 再逐步体验执行器控制和传感器应用。
#
# 本文件仅作入门说明，不会连接或控制设备。实际操作请从 02-connection.py 开始，
# 并在运行电机例程前按硬件手册完成接线，确认机构周围没有障碍物。
# 全新设备内置出厂 Token，可直接用于 USB 首次连接，不需要先配网；如果已经修改
# 过 Token，后续例程应使用设备当前保存的值。
